from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import Command, FindExecutable, LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue
from launch_ros.substitutions import FindPackageShare


def generate_launch_description():
    # Any xacro in urdf/, e.g. model:=rover_arm_real.xacro. rover_arm_raw.xacro uses
    # relative mesh paths straight from LinkForge, which RViz can't resolve.
    model_arg = DeclareLaunchArgument(
        'model',
        default_value='rover_arm_sim.xacro',
        description='Arm xacro file in rover_arm_description/urdf to display',
    )
    xacro_file = PathJoinSubstitution([
        FindPackageShare('rover_arm_description'), 'urdf', LaunchConfiguration('model')
    ])
    robot_description = ParameterValue(
        Command([FindExecutable(name='xacro'), ' ', xacro_file]), value_type=str
    )

    return LaunchDescription([
        model_arg,
        Node(
            package='robot_state_publisher',
            executable='robot_state_publisher',
            parameters=[{'robot_description': robot_description}]
        ),
        Node(
            package='joint_state_publisher_gui',
            executable='joint_state_publisher_gui',
        ),
        Node(
            package='rviz2',
            executable='rviz2',
        ),
    ])

