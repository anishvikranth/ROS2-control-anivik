from launch import LaunchDescription
from launch_ros.actions import Node
from launch.substitutions import Command, FindExecutable, PathJoinSubstitution
from launch_ros.substitutions import FindPackageShare

def generate_launch_description():
    #Path to the xacro file for the robot description
    xacro_file = PathJoinSubstitution([
        FindPackageShare('rover_arm_description'), 'urdf', 'test_arm.xacro'
    ])  #Tells the launch file where to find the xacro file for the robot description
    robot_description = Command([FindExecutable(name='xacro'), ' ', xacro_file])
#robot_description is a parameter that contains the robot description in URDF format, 
# which is generated by processing the xacro file using the xacro command.

    return LaunchDescription([
        Node(
            package='robot_state_publisher',
            executable='robot_state_publisher',
            parameters=[{'robot_description': robot_description}]
        ),
        Node(
            package='joint_state_publisher_gui',
            executable='joint_state_publisher_gui',
        ),
        Node(
            package='rviz2',
            executable='rviz2',
        ),
    ])